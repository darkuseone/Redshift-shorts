"""Смысл блока сценария: какие признаки в нём есть и что из них следует.

Приём ставится по смыслу, а не по роли блока (§3.1 `instruction.md`). Роль
говорит, *где* мы в ролике; признак говорит, *что* в кадре можно показать.
Карточка числа нужна там, где число названо; окно переписки — где задан
вопрос; разворот статьи — где есть цитата. Нечем наполнить приём — приёма нет.

Признаки нарочно грубые и проверяемые по тексту. Тонкую семантику здесь не
разобрать без модели, а модель на каждый блок — это цена прогона и лишняя
зависимость там, где хватает регулярного выражения.

**Числа пишутся словами.** Первый же замер по нашим шести сценариям это и
показал: цифр в тексте почти нет, потому что TTS озвучивает «двенадцать тысяч
двести шестьдесят два», а не «12262». Регулярка на ``\\d`` находила признак в
6 % блоков, со словами-числительными — в 25 %.
"""

from __future__ import annotations

import re
from typing import Any, Iterable

# --- словарь признаков -------------------------------------------------------

# Числительные словами: без них признак «число» не находится почти нигде.
_NUMBER_WORDS = (
    r"ноль|один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|"
    r"одиннадцать|двенадцать|тринадцать|четырнадцать|пятнадцать|шестнадцать|"
    r"семнадцать|восемнадцать|девятнадцать|двадцат\w*|тридцат\w*|сорок\w*|"
    r"пятьдесят|шестьдесят|семьдесят|восемьдесят|девяносто|сто|двест\w*|трист\w*|"
    r"четырест\w*|пятьсот|шестьсот|семьсот|восемьсот|девятьсот|тысяч\w*|"
    r"миллион\w*|миллиард\w*|процент\w*|десятк\w*|сотн\w*|половин\w*|треть|четверть"
)

TRAIT_PATTERNS: dict[str, str] = {
    # Есть что показать цифрой: счётчик, карточка числа, столбик.
    "number": r"\d|\b(?:%s)\b" % _NUMBER_WORDS,
    # Две величины рядом: сплит, «против», «вместо».
    "comparison": (r"\bв \w+ раз\b|больше,? чем|меньше,? чем|вместо|против\b|"
                   r"\bа не\b|зато\b|тогда как|вдвое|втрое|вчетверо|"
                   r"с одной стороны|разниц\w+ в\b"),
    # Вопрос в реплике: окно переписки, вопрос вспышкой.
    "question": r"\?|\bпочему\b|\bзачем\b|как так|что если|правда ли|\bсколько\b",
    # Прямая речь или цитата источника: разворот статьи, карточка препринта.
    "quote": r"[«\"][^»\"]{8,}[»\"]|по словам|цитирую|сообщает\w*|пишет\w*\s+в\b",
    # Перечисление: список, который копится строкой за строкой.
    "list": (r"во-первых|первое[,:]|второе[,:]|третье[,:]|\bсписок\b|"
             r"(?:\b\w+\b,\s+){3,}\b\w+\b|и\s+ещё\b|а\s+также\b"),
    # Год, век, срок: шкала времени, датированная карточка.
    "date": r"\b(?:19|20)\d\d\b|\bгоду\b|\bвеке\b|\bлет\b|\bдесятилети",
    # Имя компании или продукта: плашка знака бренда.
    "brand": (r"\b(?:OpenAI|Google|NASA|ESA|Apple|ChatGPT|Gemini|SpaceX|Nvidia|"
              r"Microsoft|Meta|Tesla|Amazon|DeepMind|Boston Dynamics|Roscosmos|"
              r"Роскосмос|Яндекс|Сбер|IBM|Intel|AMD|Anthropic|Claude)\b"),
    # Отрицание: «дело не в этом» — приговор, выбивка, перечёркнутое слово.
    # Голое «не» стоит в трети блоков и ничего не значит: «не только»,
    # «не совсем». Признаком считается отрицание по существу — то, вокруг
    # чего строится реплика.
    "negation": (r"дело не в|не из-за|не потому|не так,? как|так и не\b|\bнет\b|"
                 r"никт\w+|ничего|нельзя|невозможн\w*|перестал\w*|отказал\w*|"
                 r"провал\w*|не сработал\w*|не нашли|не смогли|не удалось"),
    # Превосходная степень: рекорд, впервые, единственный.
    "superlative": (r"самы[йяоеы]\w*|впервые|единственн\w+|рекорд\w*|крупнейш\w+|"
                    r"глубочайш\w+|быстрейш\w+|\bпервый\b|\bлучш\w+"),
    # Опасность и провал: тревожный кадр, красный акцент.
    "danger": r"опасн\w*|риск\w*|угроз\w*|катастроф\w*|авари\w*|погиб\w*|сгорел\w*|взорв\w*",
    # Находка: «оказалось», «выяснилось» — момент разворота.
    "discovery": (r"обнаружил\w*|нашли|нашёл|оказал\w+сь|выяснил\w*сь|показал\w*|"
                  r"доказал\w*|поняли|увидели|заметил\w*"),
    # Деньги: бюджет, стоимость, финансирование.
    "money": r"\$|доллар\w*|рубл\w*|евро\b|бюджет\w*|стоил\w*|финансир\w*|инвестиц\w*",
    # Устройство и техника: экспонат в раме, схема.
    "device": (r"машин\w*|аппарат\w*|устройств\w*|буров\w*|прибор\w*|двигател\w*|"
               r"чип\w*|процессор\w*|спутник\w*|телескоп\w*|реактор\w*|робот\w*"),
    # Место и масштаб: карта, разрез, орбита.
    "place": (r"на Земле|в космосе|орбит\w*|глубин\w*|под землёй|на Марсе|на Луне|"
              r"в океане|километр\w*|\bслой\b|\bкор[аеы]\b"),
    # Ритм / дроп — для beat-freeze-cut и музыкальных приёмов.
    "beat": r"\bбит\b|ритм\w*|\bдроп\b|на счёт|\bтакт\b|\bbeat\b|\bdrop\b",
    # Новостная лента / заголовки агентств — для news-ticker.
    "news": (r"новост\w*|заголовк\w*|лент[аы] новостей|сообщ\w+ агентств|"
             r"\bbreaking\b|\bheadline\w*"),
}

TRAITS: tuple[str, ...] = tuple(TRAIT_PATTERNS)

# Как признак называется в отчёте: он читается человеком, а не машиной.
TRAIT_TITLES: dict[str, str] = {
    "number": "названо число",
    "comparison": "сравниваются две величины",
    "question": "задан вопрос",
    "quote": "есть цитата или ссылка на источник",
    "list": "идёт перечисление",
    "date": "названа дата или срок",
    "brand": "назван бренд",
    "negation": "отрицание: «не», «нет», «перестали»",
    "superlative": "превосходная степень: рекорд, впервые",
    "danger": "речь об опасности или провале",
    "discovery": "момент находки: «оказалось», «выяснилось»",
    "money": "названы деньги",
    "device": "речь об устройстве или технике",
    "place": "названо место или масштаб",
    "beat": "ритм, бит, дроп",
    "news": "новости, заголовки, лента",
}

_COMPILED = {name: re.compile(pattern, re.IGNORECASE)
             for name, pattern in TRAIT_PATTERNS.items()}


def block_traits(text: str) -> frozenset[str]:
    """Признаки одного блока сценария.

    Пустой набор — законный ответ: у трети блоков наших сценариев признаков
    нет вовсе, и это значит ровно одно — приём такому блоку не нужен.
    """
    body = str(text or "")
    return frozenset(name for name, rx in _COMPILED.items() if rx.search(body))


def traits_of_block(block: dict[str, Any]) -> frozenset[str]:
    """Признаки блока плана: текст плюс то, что уже посчитано раньше."""
    saved = block.get("traits")
    if saved:
        return frozenset(str(t) for t in saved)
    return block_traits(block.get("text") or block.get("spoken_text") or "")


def explain(traits: Iterable[str]) -> str:
    """Признаки словами — для поля «почему» в плане и отчёте."""
    names = [TRAIT_TITLES.get(t, t) for t in sorted(traits)]
    return ", ".join(names) if names else "признаков нет"


def satisfies(needs: Iterable[str], traits: Iterable[str]) -> bool:
    """Годится ли приём блоку.

    ``needs`` — «хотя бы один из»: приёму хватает одного основания. Приём без
    требований годится всегда: движение кадра, переход и вход аватара смысла
    не несут и наполнения не требуют.
    """
    wanted = {str(n) for n in needs if n}
    if not wanted:
        return True
    return bool(wanted & {str(t) for t in traits})


def matched(needs: Iterable[str], traits: Iterable[str]) -> frozenset[str]:
    """Чем именно приём оправдан в этом блоке."""
    return frozenset({str(n) for n in needs if n} & {str(t) for t in traits})
