"""Слова-паразиты: что вырезается молча, а что выносится человеку.

Речь ролика — TTS нашего же сценария, поэтому паразит попадает в звук
единственным путём: мы его написали. Значит, и ловить его надо в тексте, до
синтеза, а не оперировать потом звук.

Список разделён надвое, и это не придирка, а вывод из проверки.

*Запинки* (`HESITATIONS`) — «эээ», «ммм» — значения не несут ни в какой
позиции. Их убирают молча: ошибиться тут нечем.

*Вводные слова* (`DISCOURSE`) — «ну», «типа», «короче» — паразиты
только в позиции паразита, а определить её по соседям нельзя. Первая версия
пробовала: «вводное в начале фразы или перед запятой». На пяти примерах она
сломала два. «Вот это поворот» → «Это поворот»: «вот» здесь усилитель, а не
затычка. «Это значит, что вселенная расширяется» → «Это что вселенная
расширяется»: съеден сказуемый глагол — фраза перестала быть фразой.

Поэтому вводные слова **не режутся**. `discourse_hits` их находит и
возвращает; решение принимает человек, переписав фразу. Пропущенный паразит —
мелочь, съеденное значимое слово — брак, который слышно, и цена ошибки в этих
двух случаях несопоставима.
"""

from __future__ import annotations

import re

# Звуки-запинки. Смысла не несут, вырезаются безусловно.
HESITATIONS: frozenset[str] = frozenset({
    "э", "ээ", "эээ", "эм", "эмм", "мм", "ммм", "ааа", "нуу", "нууу",
})

# Вводные слова и обороты. Только для отчёта — см. модульную справку.
#
# Список нарочно короткий: в нём то, что в сценарии почти всегда вата. «Вот»,
# «значит» и «получается» отсюда убраны — проверка на сценариях репозитория
# сработала на «И вот ответ на вопрос», где «вот» держит фразу. Предупреждение,
# которое врёт на верном тексте, перестают читать, и тогда оно не стоит ничего.
DISCOURSE: tuple[str, ...] = (
    "как бы", "в общем", "так сказать", "это самое",
    "ну", "типа", "короче", "собственно",
)

_PUNCT = ".,!?;:…«»\"'—–-"


def normal(word: str) -> str:
    """Слово к виду, в котором его ищут в списках."""
    return word.strip(_PUNCT).strip().lower().replace("ё", "е")


def is_hesitation(word: str) -> bool:
    """Запинка ли это. Единственное, что вырезается без участия человека."""
    return normal(word) in HESITATIONS


def strip_hesitations(text: str) -> tuple[str, list[str]]:
    """Убрать запинки из текста сценария до синтеза.

    Возвращает (текст, что убрано). Если фраза состояла из одних запинок, она
    остаётся как есть: пустая реплика — это вопрос к автору, а не к чистке.
    """
    words = text.split()
    kept = [w for w in words if not is_hesitation(w)]
    dropped = [w for w in words if is_hesitation(w)]
    if not kept:
        return text, []

    out = " ".join(kept)
    # Убранная запинка не должна оставлять фразу со строчной буквы.
    if dropped and out[:1].islower() and text[:1].isupper():
        out = out[0].upper() + out[1:]
    # И не должна оставлять висящую запятую в начале: «Эээ, свет» → «Свет».
    out = re.sub(r"^[,;]\s*", "", out)
    return out, dropped


def discourse_hits(text: str) -> list[str]:
    """Вводные слова, найденные в тексте, — для отчёта, а не для выреза.

    Порядок в `DISCOURSE` важен: обороты идут раньше одиночных слов, иначе
    «в общем» нашлось бы как «общем» мимо оборота.
    """
    plain = " " + re.sub(r"[^\w\s]", " ", text.lower().replace("ё", "е")) + " "
    hits: list[str] = []
    for phrase in DISCOURSE:
        if f" {phrase} " in plain:
            hits.append(phrase)
            plain = plain.replace(f" {phrase} ", " ")
    return hits
