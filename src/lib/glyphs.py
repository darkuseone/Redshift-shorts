# Основа короче этого совпадает только словом целиком. Длина здесь про
# **основу**, а не про слово: «чип» — настоящее слово и настоящий знак, а
# защита от служебных слов, поставленная на длину слова, выбрасывала его
# вместе с «это» и «на».
_LOOSE_STEM = 4


def _bare(word: str) -> str:
    return word.strip(".,!?;:»«\"'()—–-").lower()


def _hits(bare: str, stems: tuple[str, ...]) -> bool:
    return any(bare.startswith(stem) if len(stem) >= _LOOSE_STEM else bare == stem
               for stem in stems)


def match_glyphs(text: str, *, limit: int = 6) -> list[str]:
    """Знаки, которые реплика действительно заслужила.

    Порядок — по тексту, а не по словарю: знаки идут в том же порядке, в каком
    произносится то, что они обозначают. Один знак на реплику не повторяется:
    два одинаковых чипа за головой читаются как сбой, а не как ритм.
    """
    seen: list[str] = []
    for word in str(text).split():
        bare = _bare(word)
        if not bare:
            continue
        for name, glyph in GLYPHS.items():
            if name in seen:
                continue
            if _hits(bare, glyph["stems"]):                    # type: ignore[arg-type]
                seen.append(name)
                break
        if len(seen) >= limit:
            break
    return seen


def glyph_svg(name: str, *, size: int = 48) -> str:
    """Разметка знака. Пустая строка — если знака с таким именем нет."""
    glyph = GLYPHS.get(name)
    if not glyph:
        return ""
    return (f'<svg viewBox="0 0 48 48" width="{size}" height="{size}" '
            f'fill="none" stroke="currentColor" stroke-width="3" '
            f'stroke-linecap="round" stroke-linejoin="round">'
            f'{glyph["svg"]}</svg>')


def names() -> Iterable[str]:
    return GLYPHS.keys()
